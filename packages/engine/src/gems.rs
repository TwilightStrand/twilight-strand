pub fn lookup_gem_at_level(skill_id: &str, level: u32) -> Option<GemData> {
    let canonical = ALIASES.get(skill_id).copied().unwrap_or(skill_id);
    let entry = GEM_JSON.get(canonical)?;

    if entry.is_support {
        return None;
    }

    let lvl = get_json_level_data(entry, level)?;
    let tags = tags_from_json(entry);
    let overrides = OVERRIDES.get(canonical);

    let dot_base = if entry.is_dot && lvl.spell_damage_more_pct > 0.0 {
        let l20_pct = entry.levels.get("20")
            .map(|l| l.spell_damage_more_pct)
            .unwrap_or(lvl.spell_damage_more_pct);
        if l20_pct > 0.0 { 100.0 * lvl.spell_damage_more_pct / l20_pct } else { 0.0 }
    } else if lvl.dot_dpm > 0.0 {
        lvl.dot_dpm / 60.0
    } else {
        0.0
    };

    let damage_types: Vec<DamageType> = entry.damage_types.iter()
        .map(|s| parse_damage_type(s))
        .collect();

    Some(GemData {
        skill_id: entry.skill_id.clone(),
        name: entry.name.clone(),
        base_damages: lvl.damages,
        base_crit_chance: lvl.crit_chance,
        base_cast_time: entry.cast_time,
        damage_effectiveness: lvl.damage_effectiveness,
        tags,
        is_dot: entry.is_dot || lvl.dot_dpm > 0.0,
        dot_base,
        damage_types,
        base_multiplier: lvl.base_multiplier,
        attack_speed_multiplier: lvl.attack_speed_multiplier,
        stages: overrides.map_or(0, |o| o.stages),
        base_totem_count: overrides.map_or(0, |o| o.base_totem_count),
    })
}

pub fn lookup_gem(skill_id: &str) -> Option<GemData> {
    lookup_gem_at_level(skill_id, 20)
}

pub fn gem_count() -> usize {
    GEM_JSON.values().filter(|e| !e.is_support).count()
}

/// Look up a support gem's modifiers at a specific level.
/// Returns the pre-computed modifier list from the JSON, or None if not found.
pub fn lookup_support_mods(skill_id: &str, level: u32) -> Option<(Vec<SupportMod>, Vec<SupportMod>)> {
    let entry = GEM_JSON.get(skill_id)?;
    if !entry.is_support { return None; }

    let key = level.to_string();
    let lvl = entry.levels.get(&key).or_else(|| {
        entry.levels.get("20")
    })?;

    Some((lvl.mods.clone(), entry.constant_mods.clone()))
}

/// Get the display name -> skill_id mapping for all support gems.
pub fn support_name_index() -> &'static HashMap<String, String> {
    static INDEX: LazyLock<HashMap<String, String>> = LazyLock::new(|| {
        let mut m = HashMap::new();
        // Insert non-awakened first, then awakened (full name only)
        // so short-name lookups always resolve to the base variant
        let mut entries: Vec<_> = GEM_JSON.iter()
            .filter(|(_, e)| e.is_support)
            .collect();
        entries.sort_by_key(|(id, _)| if id.contains("Awakened") { 1 } else { 0 });

        for (skill_id, entry) in entries {
            let full = entry.name.to_lowercase();
            let is_awakened = skill_id.contains("Awakened") || full.contains("awakened");

            m.insert(full.clone(), skill_id.clone());
            m.insert(skill_id.to_lowercase(), skill_id.clone());

            if !is_awakened {
                let short = full.replace(" support", "");
                m.insert(short, skill_id.clone());
            }
        }
        m
    });
    &INDEX
}

