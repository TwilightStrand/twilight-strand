#[derive(Deserialize)]
struct GemJsonEntry {
    skill_id: String,
    name: String,
    is_support: bool,
    #[serde(default)]
    is_attack: bool,
    #[serde(default)]
    is_dot: bool,
    #[serde(default)]
    is_minion: bool,
    #[serde(default)]
    cast_time: f64,
    #[serde(default)]
    damage_types: Vec<String>,
    #[serde(default)]
    tags: Vec<String>,
    #[serde(default)]
    levels: HashMap<String, GemJsonLevel>,
    // Support-specific fields
    #[serde(default)]
    constant_mods: Vec<SupportMod>,
}

#[derive(Deserialize)]
struct GemJsonLevel {
    #[serde(default)]
    level_requirement: u32,
    #[serde(default)]
    crit_chance: f64,
    #[serde(default)]
    damage_effectiveness: f64,
    #[serde(default)]
    damages: Vec<GemJsonDamage>,
    #[serde(default)]
    base_multiplier: f64,
    #[serde(default)]
    attack_speed_multiplier: f64,
    #[serde(default)]
    dot_dpm: f64,
    #[serde(default)]
    spell_damage_more_pct: f64,
    // Support-specific
    #[serde(default)]
    mana_multiplier: i32,
    #[serde(default)]
    mods: Vec<SupportMod>,
}

#[derive(Clone, Deserialize, Debug)]
pub struct SupportMod {
    pub stat: String,
    #[serde(rename = "type")]
    pub mod_type: String,
    pub value: f64,
    #[serde(default)]
    pub flags: Option<String>,
}

#[derive(Deserialize)]
struct GemJsonDamage {
    damage_type: String,
    min: f64,
    max: f64,
}

static GEM_JSON_RAW: &str = include_str!("../data/gems.json");

static GEM_JSON: LazyLock<HashMap<String, GemJsonEntry>> = LazyLock::new(|| {
    serde_json::from_str(GEM_JSON_RAW).expect("gems.json should be valid")
});

